drop function if exists public.get_booked_slots(date);

create function public.get_booked_slots(target_date date)
returns table (appointment_time time)
language sql
security definer
set search_path = public
as $$
  update public.appointments
  set status = 'Expirado', payment_status = 'Expirado', updated_at = now()
  where status = 'Aguardando pagamento'
    and expires_at is not null
    and expires_at <= now();

  select a.appointment_time
  from public.appointments a
  where a.appointment_date = target_date
    and (
      a.status = 'Confirmado'
      or (a.status = 'Aguardando pagamento' and a.expires_at > now())
    )
  order by a.appointment_time;
$$;

grant execute on function public.get_booked_slots(date) to anon, authenticated;
